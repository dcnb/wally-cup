// Bundles js/main.js into one classic script so the game opens by double-clicking play.html (no server).
// Usage: node tools/bundle.mjs   (re-run after editing anything in js/)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mods = new Map(); // abs path -> { id, code }

function load(abs) {
  if (mods.has(abs)) return mods.get(abs).id;
  const id = './' + path.relative(root, abs);
  const entry = { id, code: '' };
  mods.set(abs, entry);
  let src = fs.readFileSync(abs, 'utf8');
  const exportsList = [];
  // import { a, b as c } from './x.js';
  src = src.replace(/^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*$/gm, (_, names, spec) => {
    const dep = load(path.resolve(path.dirname(abs), spec));
    const list = names.split(',').map((s) => s.trim()).filter(Boolean).map((s) => s.replace(/\s+as\s+/, ': '));
    return `const { ${list.join(', ')} } = __req(${JSON.stringify(dep)});`;
  });
  // export { a, b };
  src = src.replace(/^export\s*\{([^}]*)\};?[ \t]*$/gm, (_, names) => {
    names.split(',').map((s) => s.trim()).filter(Boolean).forEach((n) => exportsList.push(n));
    return '';
  });
  // export const/let/function/class name
  src = src.replace(/^export\s+(const|let|var|function|class|async function)\s+([A-Za-z_$][\w$]*)/gm, (_, kw, name) => {
    exportsList.push(name);
    return `${kw} ${name}`;
  });
  if (/^\s*(import|export)\s/m.test(src.replace(/\/\/.*$/gm, ''))) throw new Error('Unhandled import/export syntax in ' + id);
  entry.code = `${src}\nreturn { ${exportsList.join(', ')} };`;
  return id;
}

const entry = load(path.join(root, 'js/main.js'));
let out = '// GENERATED by tools/bundle.mjs - do not edit. Edit js/ and re-run the script.\n(function () {\nconst __defs = {}, __cache = {};\nfunction __req(id) { if (!(id in __cache)) { __cache[id] = {}; __cache[id] = __defs[id](); } return __cache[id]; }\n';
for (const { id, code } of mods.values()) out += `__defs[${JSON.stringify(id)}] = function () {\n${code}\n};\n`;
out += `__req(${JSON.stringify(entry)});\n})();\n`;
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist/game.js'), out);

const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8')
  .replace('<script type="module" src="js/main.js"></script>', '<script src="dist/game.js"></script>');
if (!html.includes('dist/game.js')) throw new Error('script tag not found in index.html');
fs.writeFileSync(path.join(root, 'play.html'), html);
console.log(`bundled ${mods.size} modules -> dist/game.js, play.html`);
